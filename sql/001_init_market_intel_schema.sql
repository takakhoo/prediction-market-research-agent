BEGIN;

CREATE TABLE IF NOT EXISTS markets (
  market_id TEXT PRIMARY KEY,
  condition_id TEXT,
  question_id TEXT,
  event_id TEXT,
  event_slug TEXT,
  slug TEXT,
  question TEXT NOT NULL,
  description TEXT,
  rules_text TEXT,
  market_context TEXT,
  market_archetype TEXT NOT NULL DEFAULT 'binary_unknown',
  is_local_candidate BOOLEAN,
  local_score NUMERIC(6, 5),
  local_reason_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  closed BOOLEAN NOT NULL DEFAULT FALSE,
  archived BOOLEAN NOT NULL DEFAULT FALSE,
  accepting_orders BOOLEAN,
  enable_order_book BOOLEAN,
  high_competition BOOLEAN,
  end_date TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  rules_hash TEXT,
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT markets_local_score_range CHECK (
    local_score IS NULL OR (local_score >= 0.0 AND local_score <= 1.0)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_markets_slug_unique
  ON markets (slug)
  WHERE slug IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_markets_active_closed
  ON markets (active, closed);

CREATE INDEX IF NOT EXISTS idx_markets_last_seen_at
  ON markets (last_seen_at DESC);

ALTER TABLE markets ADD COLUMN IF NOT EXISTS high_competition BOOLEAN;

CREATE TABLE IF NOT EXISTS market_outcomes (
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  outcome_index INTEGER NOT NULL,
  outcome_label TEXT NOT NULL,
  token_id TEXT,
  price NUMERIC(12, 6),
  probability NUMERIC(12, 6),
  is_likely BOOLEAN,
  is_unlikely BOOLEAN,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (market_id, outcome_index),
  CONSTRAINT market_outcomes_probability_range CHECK (
    probability IS NULL OR (probability >= 0.0 AND probability <= 1.0)
  )
);

CREATE INDEX IF NOT EXISTS idx_market_outcomes_market_id
  ON market_outcomes (market_id);

CREATE TABLE IF NOT EXISTS market_snapshots (
  snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  observed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  best_bid NUMERIC(12, 6),
  best_ask NUMERIC(12, 6),
  last_trade_price NUMERIC(12, 6),
  volume_usd NUMERIC(18, 2),
  liquidity_usd NUMERIC(18, 2),
  spread NUMERIC(12, 6),
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_market_snapshots_market_observed
  ON market_snapshots (market_id, observed_at DESC);

CREATE TABLE IF NOT EXISTS market_analysis (
  analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  analyzed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  analysis_version TEXT NOT NULL DEFAULT 'v1',
  prompt_version TEXT,
  rules_hash TEXT,
  is_local BOOLEAN NOT NULL,
  local_score NUMERIC(6, 5),
  classification TEXT,
  reason_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'active',
  CONSTRAINT market_analysis_local_score_range CHECK (
    local_score IS NULL OR (local_score >= 0.0 AND local_score <= 1.0)
  )
);

CREATE INDEX IF NOT EXISTS idx_market_analysis_market_analyzed
  ON market_analysis (market_id, analyzed_at DESC);

CREATE TABLE IF NOT EXISTS telegram_channels (
  chat_id BIGINT PRIMARY KEY,
  title TEXT NOT NULL,
  username TEXT,
  description TEXT,
  member_count INTEGER,
  language_hint TEXT[] NOT NULL DEFAULT '{}'::text[],
  is_public BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  trust_weight NUMERIC(6, 5) NOT NULL DEFAULT 0.50000,
  tags_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  notes TEXT NOT NULL DEFAULT '',
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT telegram_channels_trust_weight_range CHECK (
    trust_weight >= 0.0 AND trust_weight <= 1.0
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_telegram_channels_username_unique
  ON telegram_channels (username)
  WHERE username IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_telegram_channels_last_seen
  ON telegram_channels (last_seen_at DESC);

CREATE TABLE IF NOT EXISTS channel_market_map (
  chat_id BIGINT NOT NULL REFERENCES telegram_channels(chat_id) ON DELETE CASCADE,
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  link_source TEXT NOT NULL DEFAULT 'auto',
  link_status TEXT NOT NULL DEFAULT 'active',
  priority_rank INTEGER,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (chat_id, market_id)
);

CREATE INDEX IF NOT EXISTS idx_channel_market_map_market
  ON channel_market_map (market_id, link_status);

CREATE INDEX IF NOT EXISTS idx_channel_market_map_chat
  ON channel_market_map (chat_id, link_status);

CREATE TABLE IF NOT EXISTS telegram_messages (
  chat_id BIGINT NOT NULL REFERENCES telegram_channels(chat_id) ON DELETE CASCADE,
  message_id BIGINT NOT NULL,
  posted_at TIMESTAMPTZ,
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  text TEXT NOT NULL DEFAULT '',
  language TEXT,
  has_media BOOLEAN NOT NULL DEFAULT FALSE,
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (chat_id, message_id)
);

CREATE INDEX IF NOT EXISTS idx_telegram_messages_posted_at
  ON telegram_messages (posted_at DESC);

CREATE INDEX IF NOT EXISTS idx_telegram_messages_ingested_at
  ON telegram_messages (ingested_at DESC);

CREATE TABLE IF NOT EXISTS message_market_matches (
  match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id BIGINT NOT NULL,
  message_id BIGINT NOT NULL,
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  evaluated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  is_match BOOLEAN NOT NULL,
  matched_outcome_index INTEGER,
  match_reason_short TEXT,
  matcher_version TEXT NOT NULL DEFAULT 'v1',
  raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT message_market_matches_fk_message
    FOREIGN KEY (chat_id, message_id)
    REFERENCES telegram_messages(chat_id, message_id)
    ON DELETE CASCADE,
  UNIQUE (chat_id, message_id, market_id)
);

CREATE INDEX IF NOT EXISTS idx_message_market_matches_market
  ON message_market_matches (market_id, evaluated_at DESC);

CREATE INDEX IF NOT EXISTS idx_message_market_matches_chat
  ON message_market_matches (chat_id, evaluated_at DESC);

CREATE INDEX IF NOT EXISTS idx_message_market_matches_is_match
  ON message_market_matches (is_match, evaluated_at DESC);

CREATE TABLE IF NOT EXISTS market_activations (
  activation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id TEXT NOT NULL REFERENCES markets(market_id) ON DELETE CASCADE,
  activation_time TIMESTAMPTZ NOT NULL,
  trigger_chat_id BIGINT NOT NULL,
  trigger_message_id BIGINT NOT NULL,
  trigger_match_id BIGINT REFERENCES message_market_matches(match_id) ON DELETE SET NULL,
  activation_source TEXT NOT NULL DEFAULT 'telegram_match',
  notes TEXT NOT NULL DEFAULT '',
  UNIQUE (market_id),
  CONSTRAINT market_activations_fk_message
    FOREIGN KEY (trigger_chat_id, trigger_message_id)
    REFERENCES telegram_messages(chat_id, message_id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_market_activations_time
  ON market_activations (activation_time DESC);

CREATE TABLE IF NOT EXISTS channel_leaderboard_daily (
  leaderboard_date DATE NOT NULL,
  chat_id BIGINT NOT NULL REFERENCES telegram_channels(chat_id) ON DELETE CASCADE,
  markets_hit INTEGER NOT NULL DEFAULT 0,
  matched_messages INTEGER NOT NULL DEFAULT 0,
  evaluated_messages INTEGER NOT NULL DEFAULT 0,
  relevance_ratio NUMERIC(12, 6) NOT NULL DEFAULT 0.0,
  rank_points NUMERIC(12, 6) NOT NULL DEFAULT 0.0,
  speed_score NUMERIC(12, 6) NOT NULL DEFAULT 0.0,
  coverage_score NUMERIC(12, 6) NOT NULL DEFAULT 0.0,
  total_score NUMERIC(12, 6) NOT NULL DEFAULT 0.0,
  computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (leaderboard_date, chat_id)
);

CREATE INDEX IF NOT EXISTS idx_channel_leaderboard_daily_score
  ON channel_leaderboard_daily (leaderboard_date, total_score DESC);

CREATE TABLE IF NOT EXISTS telegram_backtest_runs (
  run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  market_ref TEXT NOT NULL,
  market_id TEXT,
  market_slug TEXT,
  params_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  summary_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  payload_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_telegram_backtest_runs_created
  ON telegram_backtest_runs (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_telegram_backtest_runs_market
  ON telegram_backtest_runs (market_ref, market_slug, market_id);

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_markets_set_updated_at ON markets;
CREATE TRIGGER trg_markets_set_updated_at
BEFORE UPDATE ON markets
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_channel_market_map_set_updated_at ON channel_market_map;
CREATE TRIGGER trg_channel_market_map_set_updated_at
BEFORE UPDATE ON channel_market_map
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMIT;
